// =============================================================================
// ファイル: excel_ajsprint.go
// 概要: JP1/AJSユニット定義プリントシート（Ajsprint）の更新機能を提供
// 機能:
//   - ユニット定義データをExcelシートに書き込む
//   - 連番列（B列）とデータ列（C列）にスタイルを適用する
//
// =============================================================================
package main

import (
	"fmt" // 書式付き出力用（エラー表示、セルアドレス生成）

	"github.com/xuri/excelize/v2" // Excelファイル操作ライブラリ
)

// =============================================================================
// update_sheet_ajsprint: JP1/AJSユニット定義をExcelのAjsprintシートに書き込む
// =============================================================================
// 引数:
//   - f: Excelファイルオブジェクト
//   - data: ユニット定義データの配列（各行の文字列）
//   - styles: スタイルIDを格納するマップ
//   - "style1": 連番列（B列）用スタイルID（中央揃え）
//   - "style2": データ列（C列）用スタイルID（左揃え）
//
// 処理概要:
//  1. dataの各要素をシートの4行目以降に書き込む
//  2. B列（連番）にstyle1を適用
//  3. C列（ユニット定義データ）にstyle2を適用
//
// 対象シート: "Ajsprint"
// データ開始行: 4行目（1〜3行目はヘッダー領域）
// 列構成:
//   - B列: 連番（1, 2, 3, ...）
//   - C列: ユニット定義データ（各行の内容）
func update_sheet_ajsprint(f *excelize.File, data []string, styles map[string]int) {
	// -------------------------------------------------------------------------
	// 定数・変数の定義
	// -------------------------------------------------------------------------
	const sheet = "Ajsprint" // 対象シート名
	var cellref string = ""  // セルアドレス（動的に計算）

	// -------------------------------------------------------------------------
	// データの書き込み
	// 各ユニット定義レコードをシートの4行目以降に書き込む
	// -------------------------------------------------------------------------
	for i, v := range data {
		// 書き込み開始セルを計算
		// B列（列番号2）から開始、行番号は i+4（4行目から開始）
		// 例: i=0 → B4, i=1 → B5, i=2 → B6, ...
		cellref = CoordsToCellRef(2, i+4)

		// 1行分のデータを作成
		// rec[0]: 連番（1から始まる）
		// rec[1]: ユニット定義データ（行の内容）
		rec := []interface{}{
			i + 1, // 連番（1から始まる）
			v,     // ユニット定義データ内容
		}

		// Excelシートに行データを書き込む
		// SetSheetRow: 指定セルから横方向にデータを書き込む
		err := f.SetSheetRow(sheet, cellref, &rec)
		if err != nil {
			fmt.Println(err) // エラーメッセージを表示
			return           // エラーが発生した場合は処理を中断
		}
	}

	// -------------------------------------------------------------------------
	// B列（連番列）にスタイルを適用
	// -------------------------------------------------------------------------
	// スタイル適用範囲: B4 〜 B(データ件数+3)
	// 例: データ件数が10の場合 → B4:B13
	// 計算: 最後の行 = データ件数 + 開始行(4) - 1 = len(data) + 3
	endcell := fmt.Sprintf("B%d", len(data)+4-1)
	err := f.SetCellStyle(sheet, "B4", endcell, styles["style1"])
	if err != nil {
		fmt.Println(err) // エラーメッセージを表示
	}

	// -------------------------------------------------------------------------
	// C列（データ列）にスタイルを適用
	// -------------------------------------------------------------------------
	// スタイル適用範囲: C4 〜 C(データ件数+3)
	// B列と同じ行範囲に対してスタイルを適用
	endcell = fmt.Sprintf("C%d", len(data)+4-1)
	err = f.SetCellStyle(sheet, "C4", endcell, styles["style2"])
	if err != nil {
		fmt.Println(err) // エラーメッセージを表示
	}
}
