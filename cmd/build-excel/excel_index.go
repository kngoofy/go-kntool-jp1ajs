// =============================================================================
// ファイル: excel_index.go
// 概要: ExcelのIndexシートを更新する機能を提供
// 機能:
//   - Indexシートに作成日付を書き込む
//   - 日付セルのスタイルを設定する
//
// =============================================================================
package main

import (
	"fmt"  // 書式付き出力用（エラー表示）
	"time" // 日付・時刻処理用

	"github.com/xuri/excelize/v2" // Excelファイル操作ライブラリ
)

// =============================================================================
// update_sheet_index: ExcelのIndexシートを更新する
// =============================================================================
// 引数:
//   - f: Excelファイルオブジェクト
//
// 処理概要:
//  1. 現在日付を取得し、指定セルに書き込む
//  2. 日付セルにスタイル（右揃え、Meiryo UIフォント）を適用
//
// 対象シート: "Index"
// 対象セル: F3（作成日付を表示するセル）
// 日付形式: "2006.01.02"（例: "2026.01.08"）
func update_sheet_index(f *excelize.File) {
	// -------------------------------------------------------------------------
	// 定数・変数の定義
	// -------------------------------------------------------------------------
	const sheet = "Index"     // 対象シート名
	var cellref string = "F3" // 日付を書き込むセルアドレス

	// 現在日付を取得し、指定フォーマットで文字列に変換
	// Go言語の日付フォーマット: "2006.01.02" は YYYY.MM.DD を意味する
	date := time.Now().Format("2006.01.02")

	// -------------------------------------------------------------------------
	// セルに日付を書き込む
	// -------------------------------------------------------------------------
	err := f.SetCellValue(sheet, cellref, date)
	if err != nil {
		fmt.Println(err) // エラーメッセージを表示
		return           // エラーが発生した場合は処理を中断
	}

	// -------------------------------------------------------------------------
	// 日付セルのスタイルを設定
	// -------------------------------------------------------------------------
	// スタイル定義:
	//   - 配置: 水平=右揃え、垂直=中央揃え
	//   - フォント: Meiryo UI, 11pt
	style, err := f.NewStyle(&excelize.Style{
		Alignment: &excelize.Alignment{
			Horizontal: "right",  // 水平方向: 右揃え
			Vertical:   "center", // 垂直方向: 中央揃え
		},
		Font: &excelize.Font{
			Family: "Meiryo UI", // フォントファミリー
			Size:   11,          // フォントサイズ
		},
	})

	// スタイルをセルに適用
	err = f.SetCellStyle(sheet, cellref, cellref, style)
	if err != nil {
		fmt.Println(err) // エラーメッセージを表示
	}
}
