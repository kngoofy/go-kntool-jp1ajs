// =============================================================================
// ファイル: build_data.go
// 概要: JP1/AJSユニット定義ファイルを読み込み、データモデルを構築する機能を提供
// 機能:
//   - ユニット定義ファイルのオープンと読み込み
//   - controlパッケージを使用したパース処理
//   - 抽象構文木（UnitBlock）と行データ（[]string）の取得
//
// =============================================================================
package main

import (
	"os" // ファイル操作用

	// 内部パッケージ
	"github.com/kngoofy/go-kntool-jp1ajs/pkg/control" // JP1/AJS制御ロジック（パース処理）
	"github.com/kngoofy/go-kntool-jp1ajs/pkg/model"   // JP1/AJSデータモデル
)

// =============================================================================
// build_jp1ajs_model: JP1/AJSユニット定義ファイルを読み込み、モデルを構築する
// =============================================================================
// 引数:
//   - file: ユニット定義ファイルのパス
//
// 戻り値:
//   - *model.UnitBlock: 抽象構文木のルートノード
//   - 階層構造を持つユニット定義情報を格納
//   - []string: ユニット定義ファイルの各行を格納したスライス
//   - Excelシートへの出力などに使用
//
// 処理概要:
//  1. ユニット定義ファイルをオープン
//  2. control.ParseFileでパースし、抽象構文木と行データを取得
//  3. 構築したモデルを返却
func build_jp1ajs_model(file string) (*model.UnitBlock, []string, []model.FlckUnit,
	[]model.ArParm, []model.NetUnit, []model.JobUnit) {
	// -------------------------------------------------------------------------
	// [1].JP1/AJSのユニット定義ファイルをOpen
	// -------------------------------------------------------------------------
	// 指定されたファイルパスでユニット定義ファイルを読み取りモードでオープン
	f, err := os.Open(file)
	if err != nil {
		// ファイルオープン失敗時はパニックで終了
		panic(err)
	}
	// 関数終了時にファイルを確実にクローズ
	defer f.Close()

	// -------------------------------------------------------------------------
	// [2].ユニット定義をパースし抽象構文木を組み立てる
	// -------------------------------------------------------------------------
	// control.ParseFile: ファイルを行単位で読み込み、ユニット定義の階層構造を解析
	// 戻り値:
	//   - root: 抽象構文木のルートノード（UnitBlock型）
	//   - lines: ユニット定義ファイルの各行を格納したスライス（[]string型）
	root, lines := control.ParseFile(f)
	_ = root  // 未使用警告を抑制（呼び出し元で使用）
	_ = lines // 未使用警告を抑制（呼び出し元で使用）

	flckStack := []model.FlckUnit{}
	control.FLCKList(root, &flckStack)

	arStack := []model.ArParm{}
	control.ArList(root, &arStack)

	jobStack := []model.JobUnit{}
	netStack := []model.NetUnit{}
	control.JobList(root, &jobStack, &netStack)

	// -------------------------------------------------------------------------
	// 構築したモデルを返却
	// -------------------------------------------------------------------------
	return root, lines, flckStack, arStack, netStack, jobStack
}
